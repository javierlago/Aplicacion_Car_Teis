"""Generate carteis/ui/generated/*.py from resources/ui/*.ui.

Run it after editing a .ui file in Qt Designer::

    python tools/build_ui.py

Image paths in the .ui files are relative to the .ui (so Designer shows the icons); the
generated code refers to them through the ``img:`` search path registered at start-up, so
the app finds them whatever the working directory is.
"""

import io
import re
import sys
from pathlib import Path

from PyQt6.uic import compileUi

ROOT = Path(__file__).resolve().parents[1]
UI_DIR = ROOT / "resources" / "ui"
OUT_DIR = ROOT / "carteis" / "ui" / "generated"

_IMAGE_PATH = re.compile(r'"(?:\.\./)+img/([^"]+)"')
_HEADER = "# Generated by tools/build_ui.py from resources/ui/{name}. Do not edit.\n"


def build(ui_file: Path) -> Path:
    code = io.StringIO()
    # Passing a file object (not a path) stops pyuic from prefixing the .ui directory.
    with ui_file.open(encoding="utf-8") as source:
        compileUi(source, code)
    text = _IMAGE_PATH.sub(r'"img:\1"', code.getvalue())
    text = _HEADER.format(name=ui_file.name) + text.split("\n\n", 1)[1]
    target = OUT_DIR / f"{ui_file.stem}.py"
    target.write_text(text, encoding="utf-8", newline="\n")
    return target


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "__init__.py").write_text(
        '"""Code generated from resources/ui by tools/build_ui.py."""\n', encoding="utf-8"
    )
    for ui_file in sorted(UI_DIR.glob("*.ui")):
        print(f"{ui_file.relative_to(ROOT)} -> {build(ui_file).relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
